val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

// Firma release: SOLO se activa si existe gen/android/keystore.properties.
// En CI ese archivo se genera desde los secrets universales del repo
// (ANDROID_SIGNING_KEY_BASE64, ...). En local sin el archivo, el build
// release queda sin firmar, igual que antes. Nunca se genera una llave
// nueva acá: la keystore universal es única para todo el ecosistema OWS.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        FileInputStream(keystorePropertiesFile).use { load(it) }
    }
}

